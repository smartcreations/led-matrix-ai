"""Turns a microWakeWord model (.tflite + its .json manifest) into firmware/player/wakeword_model.h.

Usage: python3 firmware/tools/model_to_header.py path/to/model.json
The .tflite file must sit next to the .json, named as in its "model" field.
"""
import json
import pathlib
import sys

manifest_path = pathlib.Path(sys.argv[1])
manifest = json.loads(manifest_path.read_text())
model = (manifest_path.parent / manifest["model"]).read_bytes()
micro = manifest["micro"]

rows = [", ".join(f"0x{b:02x}" for b in model[i : i + 16]) for i in range(0, len(model), 16)]
out = pathlib.Path(__file__).resolve().parent.parent / "player" / "wakeword_model.h"
out.write_text(
    f"""// Generated by firmware/tools/model_to_header.py from {manifest_path.name}. Do not edit.
#pragma once
#include <stdint.h>

#define WAKEWORD_NAME "{manifest["wake_word"]}"
#define WAKEWORD_CUTOFF {micro["probability_cutoff"]}f
#define WAKEWORD_WINDOW {micro["sliding_window_size"]}
#define WAKEWORD_ARENA {micro["tensor_arena_size"]}

alignas(16) const uint8_t WAKEWORD_MODEL[] = {{
  {(","+chr(10)+"  ").join(rows)}
}};
"""
)
print(f"wrote {out} ({len(model)} bytes, wake word {manifest['wake_word']!r})")
